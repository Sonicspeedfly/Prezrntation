    function t(key) {
        const loc = (typeof settingsState !== "undefined" && settingsState && settingsState.locale)
            ? settingsState.locale : "ru";
        const dict = STRINGS[loc] || STRINGS.ru;
        if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
        // fallback to ru, then key itself
        if (STRINGS.ru[key] != null) return STRINGS.ru[key];
        return key;
    }

    // Tracks the last locale we actually rendered, so settings tweaks that
    // don’t touch the locale don’t re-trigger the slide typewriter / popup.
    let _appliedLocale = null;
    function applyLocale(loc) {
        if (!STRINGS[loc]) loc = "ru";
        const changed = (loc !== _appliedLocale);
        if (!changed) return;
        _appliedLocale = loc;

        // Update html lang for screen-readers and CSS hooks
        try { document.documentElement.setAttribute("lang", loc); } catch (e) { /* ignore */ }

        // Static elements tagged with data-i18n / data-i18n-html / data-i18n-aria
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key  = el.getAttribute("data-i18n");
            const html = el.getAttribute("data-i18n-html");
            const val  = t(key);
            if (html === "1" || /_html$/.test(key)) {
                el.innerHTML = val;
            } else {
                el.textContent = val;
            }
        });
        document.querySelectorAll("[data-i18n-aria]").forEach(el => {
            const key = el.getAttribute("data-i18n-aria");
            el.setAttribute("aria-label", t(key));
        });
        // placeholder / title attributes (demo input, hint button tooltips, etc.)
        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            el.setAttribute("placeholder", t(key));
        });
        document.querySelectorAll("[data-i18n-title]").forEach(el => {
            const key = el.getAttribute("data-i18n-title");
            el.setAttribute("title", t(key));
        });
        // Let the demo overlay re-render its dynamic strings (boot lines,
        // hint text, end-screen titles, etc.) in the new locale.
        if (typeof window.__demoSyncLocale === "function") {
            try { window.__demoSyncLocale(loc); } catch (e) { /* ignore */ }
        }
        // Jury checklist follows the same locale switch.
        if (typeof window.__jurySyncLocale === "function") {
            try { window.__jurySyncLocale(loc); } catch (e) { /* ignore */ }
        }

        // Switch the live slide deck to the matching locale
        if (typeof SLIDES_BY_LOCALE !== "undefined") {
            SLIDES = SLIDES_BY_LOCALE[loc] || SLIDES_BY_LOCALE.ru;
            if (typeof current === "number" && typeof renderSlide === "function") {
                // Re-render current slide silently so the body/title/sub update without
                // re-triggering the Alice story line.
                try { renderSlide(current, { silent: true }); } catch (e) { /* ignore */ }
            }
        }

        // If the settings popup is open AND it's the SETTINGS popup, re-render it so
        // its labels follow. We detect this by checking the current popup title against
        // both the RU and EN settings titles (since we may be switching between them).
        if (typeof popupBack !== "undefined" && popupBack && popupBack.classList.contains("open")
            && typeof renderSettingsPopup === "function"
            && typeof popupTitle !== "undefined" && popupTitle) {
            const cur = popupTitle.textContent;
            if (cur === STRINGS.ru["settings.title"] || cur === STRINGS.en["settings.title"]) {
                renderSettingsPopup();
            }
        }
    }


